    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
       String cedula = JOptionPane.showInternalInputDialog(
    this.getDesktopPane(), 
    "Ingresar Cédula del Paciente", 
    "Datos del Paciente", 
    JOptionPane.QUESTION_MESSAGE
);

if (cedula != null && !cedula.isEmpty()) {
    if(OperacionesPacientes.buscar(cedula)) {
        Paciente c2 = null;
        c2 = (Paciente)OperacionesPacientes.lc.get(OperacionesPacientes.con);
        this.TextId.setText(c2.getIdPaciente());
        this.TextNombre.setText(c2.getNombrePaciente());
        this.TextEdad.setText(c2.getEdad());
        this.TextDireccion.setText(c2.getDireccion());
        this.TextTelefono.setText(c2.getTelefono());
    } else {
        JOptionPane.showInternalMessageDialog(
            this.getDesktopPane(),
            "Paciente no encontrado",
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
    }

      
        
        if (cedula == null || cedula.trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "La cédula no puede estar vacía.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        
     }   
       
    }//GEN-LAST:event_jButton3ActionPerformed

