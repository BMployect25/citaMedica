    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String fechaHora = jTextField1.getText().trim();
        String motivo = jTextField2.getText().trim();

        if (jComboBox1.getSelectedIndex() <= 0 || jComboBox2.getSelectedIndex() <= 0) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un paciente y un médico de la lista.");
        } else if (fechaHora.isEmpty() || motivo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe ingresar la fecha/hora y el motivo de la cita.");
        } else {
            String paciente = jComboBox1.getSelectedItem().toString();
            JOptionPane.showMessageDialog(this, "¡Cita registrada exitosamente para " + paciente + "!");
            limpiarCampos();
        }
    }//GEN-LAST:event_jButton1ActionPerformed
