    public void cargarPacientesYMedicos() {
        jComboBox1.removeAllItems();
        jComboBox1.addItem("Seleccione Paciente...");
        for (Paciente p : operacionesPacientes.getListaPacientes()) {
            jComboBox1.addItem(p.getCedula() + " - " + p.getNombre() + " " + p.getApellido());
        }

        jComboBox2.removeAllItems();
        jComboBox2.addItem("Seleccione Médico...");
        for (Medico m : operacionesMedicos.getListaMedicos()) {
            jComboBox2.addItem(m.getDocumento() + " - Dr(a). " + m.getNombre() + " " + m.getApellido() + " (" + m.getEspecialidad() + ")");
        }
    }

