    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String nombre = jTextField1.getText().trim();

        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe ingresar el nombre de la especialidad.");
        } else {
            JOptionPane.showMessageDialog(this, "¡Especialidad guardada exitosamente!");
            limpiarCampos();
        }
    }//GEN-LAST:event_jButton1ActionPerformed
//eliminar
    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String nombre = jTextField1.getText().trim();

        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el nombre de la especialidad a eliminar.");
        } else {
            JOptionPane.showMessageDialog(this, "Especialidad eliminada correctamente.");
            limpiarCampos();
        }
    }//GEN-LAST:event_jButton2ActionPerformed
