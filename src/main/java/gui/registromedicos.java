    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String doc = jTextField1.getText().trim();
        String nom = jTextField2.getText().trim();
        String ape = jTextField3.getText().trim();
        String esp = jComboBox1.getSelectedItem().toString();

        if (doc.isEmpty() || nom.isEmpty() || ape.isEmpty() || esp.equals("Seleccione...")) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos.");
        } else {
            boolean exito = operaciones.registrarMedico(doc, nom, ape, esp);
            if (exito) {
                JOptionPane.showMessageDialog(this, "¡Médico registrado exitosamente!");
                limpiarCampos();
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed
