    //guardar
    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String cedula = txtDocumento.getText().trim();
        String nombre = txtNombre.getText().trim();
        String apellido = txtApellido.getText().trim();
        String telefono = textTelefono.getText().trim();

        if (cedula.isEmpty() || nombre.isEmpty() || apellido.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe llenar los campos obligatorios.");
        } else {
            boolean registrado = operaciones.registrarPaciente(cedula, nombre, apellido, telefono);
            if (registrado) {
                JOptionPane.showMessageDialog(this, "¡Paciente registrado exitosamente!");
                limpiarCampos();
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    // eliminar
    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String cedula = txtDocumento.getText().trim();

        if (cedula.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese la cédula a eliminar.");
        } else {
            boolean eliminado = operaciones.eliminarPaciente(cedula);
            if (eliminado) {
                limpiarCampos();
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    //buscar
    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        String cedula = txtDocumento.getText().trim();

        if (cedula.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el número de cédula a buscar.");
        } else {
            Paciente p = operaciones.buscarPaciente(cedula);
            if (p != null) {
                txtNombre.setText(p.getNombre());
                txtApellido.setText(p.getApellido());
                textTelefono.setText(p.getTelefono());
                JOptionPane.showMessageDialog(this, "Paciente encontrado.");
            } else {
                JOptionPane.showMessageDialog(this, "El paciente no existe.");
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        // TODO add your handling code here:
            limpiarCampos();
        }

        private void limpiarCampos() {
        txtDocumento.setText("");
        txtNombre.setText("");
        txtApellido.setText("");
        textTelefono.setText("");
        txtEmail.setText("");
    }//GEN-LAST:event_jButton5ActionPerformed

