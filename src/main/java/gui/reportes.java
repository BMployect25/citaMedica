    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String fechaInicio = jTextField1.getText().trim();

        if (fechaInicio.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese la fecha inicio del reporte a eliminar.");
        } else {
            JOptionPane.showMessageDialog(this, "Reporte eliminado correctamente.");
            limpiarCampos();
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void limpiarCampos() {
        jTextField1.setText("");
        jTextField2.setText("");
        if (jComboBox1.getItemCount() > 0) jComboBox1.setSelectedIndex(0);
    }
