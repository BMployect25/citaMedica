    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        String fechaInicio = jTextField1.getText().trim();

        if (fechaInicio.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese la fecha de inicio para buscar reportes.");
        } else {
            JOptionPane.showMessageDialog(this, "Reporte encontrado para el rango ingresado.");
        }
    }//GEN-LAST:event_jButton3ActionPerformed
