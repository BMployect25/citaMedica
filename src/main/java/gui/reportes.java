    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String fechaInicio = jTextField1.getText().trim();
        String fechaFin = jTextField2.getText().trim();

        if (fechaInicio.isEmpty() || fechaFin.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe ingresar el rango de fechas (Fecha Inicio y Fecha Fin).");
        } else {
            String tipoReporte = jComboBox1.getSelectedItem().toString();
            JOptionPane.showMessageDialog(this, "¡Reporte de '" + tipoReporte + "' generado exitosamente!");
        }
    }//GEN-LAST:event_jButton1ActionPerformed
